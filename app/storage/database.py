import json
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterator

from sqlalchemy import Engine, create_engine, text
from sqlalchemy.engine import Connection

from app.core.config import settings


TERMINAL_UPLOAD_ITEM_STATUSES = ("indexed", "duplicate", "failed")
PROCESSING_UPLOAD_ITEM_STATUSES = ("queued", "saving", "parsing", "splitting", "embedding")

_engine: Engine | None = None
_engine_url: str | None = None


def _normalized_database_url() -> str:
    """读取并规范 PostgreSQL URL，不提供 SQLite fallback。"""
    database_url = settings.database_url.strip()
    if not database_url:
        raise RuntimeError(
            "DATABASE_URL is required. Configure a PostgreSQL URL such as "
            "postgresql+psycopg://user:password@localhost:5432/rag."
        )

    if database_url.startswith("postgresql://"):
        return "postgresql+psycopg://" + database_url[len("postgresql://") :]
    if not database_url.startswith("postgresql+psycopg://"):
        raise RuntimeError("DATABASE_URL must use PostgreSQL with the psycopg driver.")
    return database_url


def get_database_engine() -> Engine:
    """返回带连接池的 PostgreSQL Engine；配置变化时重建连接池。"""
    global _engine, _engine_url

    database_url = _normalized_database_url()
    if _engine is not None and _engine_url == database_url:
        return _engine

    if _engine is not None:
        _engine.dispose()

    _engine = create_engine(
        database_url,
        pool_pre_ping=True,
        pool_size=settings.database_pool_size,
        max_overflow=settings.database_max_overflow,
        pool_timeout=settings.database_pool_timeout,
    )
    _engine_url = database_url
    return _engine


def dispose_database_engine() -> None:
    """释放连接池，测试切换数据库 URL 时使用。"""
    global _engine, _engine_url
    if _engine is not None:
        _engine.dispose()
    _engine = None
    _engine_url = None


@contextmanager
def _connect() -> Iterator[Connection]:
    """开启一个短事务；正常退出提交，异常退出回滚。"""
    with get_database_engine().begin() as connection:
        yield connection


def check_database_connection() -> None:
    """启动和健康检查使用的最小 PostgreSQL 连通性检查。"""
    with _connect() as connection:
        connection.execute(text("SELECT 1"))


def init_db() -> None:
    """初始化 PostgreSQL 业务表，并兼容已经存在的旧版数据结构。"""
    table_definitions = [
        """
        CREATE TABLE IF NOT EXISTS documents (
            document_id TEXT PRIMARY KEY,
            filename TEXT NOT NULL,
            file_type TEXT NOT NULL,
            file_path TEXT NOT NULL,
            chunk_count INTEGER NOT NULL,
            created_at TEXT NOT NULL
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS messages (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            thread_id TEXT NOT NULL,
            role TEXT NOT NULL,
            content TEXT NOT NULL,
            created_at TEXT NOT NULL
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS upload_batches (
            batch_id TEXT PRIMARY KEY,
            status TEXT NOT NULL,
            total INTEGER NOT NULL,
            succeeded INTEGER NOT NULL DEFAULT 0,
            failed INTEGER NOT NULL DEFAULT 0,
            skipped INTEGER NOT NULL DEFAULT 0,
            graph_path TEXT NOT NULL DEFAULT '[]',
            duration_ms INTEGER NOT NULL DEFAULT 0,
            created_at TEXT NOT NULL,
            completed_at TEXT
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS upload_batch_items (
            item_id TEXT PRIMARY KEY,
            batch_id TEXT NOT NULL,
            document_id TEXT,
            filename TEXT NOT NULL,
            file_type TEXT NOT NULL,
            file_hash TEXT,
            file_path TEXT,
            status TEXT NOT NULL,
            error_stage TEXT,
            error_message TEXT,
            chunk_count INTEGER NOT NULL DEFAULT 0,
            duration_ms INTEGER NOT NULL DEFAULT 0,
            retry_count INTEGER NOT NULL DEFAULT 0,
            duplicate_of_document_id TEXT,
            created_at TEXT NOT NULL,
            updated_at TEXT NOT NULL,
            FOREIGN KEY (batch_id) REFERENCES upload_batches(batch_id) ON DELETE CASCADE
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS document_fingerprints (
            file_hash TEXT PRIMARY KEY,
            document_id TEXT NOT NULL,
            status TEXT NOT NULL,
            filename TEXT NOT NULL,
            file_path TEXT,
            created_at TEXT NOT NULL,
            updated_at TEXT NOT NULL
        )
        """,
    ]

    with _connect() as connection:
        for definition in table_definitions:
            connection.execute(text(definition))
        connection.execute(
            text(
                "CREATE INDEX IF NOT EXISTS idx_upload_batch_items_batch_id "
                "ON upload_batch_items(batch_id)"
            )
        )
        connection.execute(
            text(
                "CREATE INDEX IF NOT EXISTS idx_upload_batches_created_at "
                "ON upload_batches(created_at DESC)"
            )
        )
    mark_interrupted_uploads()


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _duration_ms(created_at: str | None) -> int:
    try:
        started = datetime.fromisoformat(created_at or "")
        return max(0, int((datetime.now(timezone.utc) - started).total_seconds() * 1000))
    except (TypeError, ValueError):
        return 0


def _row_dict(row: Any) -> dict[str, Any] | None:
    return dict(row) if row is not None else None


def _rows_dict(rows: Any) -> list[dict[str, Any]]:
    return [dict(row) for row in rows]


def save_document(
    document_id: str,
    filename: str,
    file_type: str,
    file_path: Path,
    chunk_count: int,
) -> None:
    """保存成功入库的文档信息；向量内容存在 Chroma。"""
    with _connect() as connection:
        connection.execute(
            text(
                """
                INSERT INTO documents
                (document_id, filename, file_type, file_path, chunk_count, created_at)
                VALUES (:document_id, :filename, :file_type, :file_path, :chunk_count, :created_at)
                ON CONFLICT (document_id) DO UPDATE SET
                    filename = EXCLUDED.filename,
                    file_type = EXCLUDED.file_type,
                    file_path = EXCLUDED.file_path,
                    chunk_count = EXCLUDED.chunk_count,
                    created_at = EXCLUDED.created_at
                """
            ),
            {
                "document_id": document_id,
                "filename": filename,
                "file_type": file_type,
                "file_path": str(file_path),
                "chunk_count": chunk_count,
                "created_at": utc_now(),
            },
        )


def get_document(document_id: str) -> dict[str, Any] | None:
    with _connect() as connection:
        row = connection.execute(
            text(
                """
                SELECT document_id, filename, file_type, file_path, chunk_count, created_at
                FROM documents
                WHERE document_id = :document_id
                """
            ),
            {"document_id": document_id},
        ).mappings().first()
    return _row_dict(row)


def delete_document_record(document_id: str) -> dict[str, Any] | None:
    """删除 PostgreSQL 中的文档记录和对应指纹，返回删除前的文档信息。"""
    with _connect() as connection:
        row = connection.execute(
            text("SELECT * FROM documents WHERE document_id = :document_id"),
            {"document_id": document_id},
        ).mappings().first()
        if not row:
            return None
        connection.execute(
            text("DELETE FROM documents WHERE document_id = :document_id"),
            {"document_id": document_id},
        )
        connection.execute(
            text("DELETE FROM document_fingerprints WHERE document_id = :document_id"),
            {"document_id": document_id},
        )
    return _row_dict(row)


def list_documents() -> list[dict]:
    """给文档列表接口和 Agent 工具使用。"""
    with _connect() as connection:
        rows = connection.execute(
            text(
                """
                SELECT document_id, filename, file_type, chunk_count, created_at
                FROM documents
                ORDER BY created_at DESC
                """
            )
        ).mappings().all()
    return _rows_dict(rows)


def count_documents() -> int:
    with _connect() as connection:
        row = connection.execute(text("SELECT COUNT(*) AS count FROM documents")).mappings().first()
    return int(row["count"])


def clear_documents() -> int:
    """清空文档元数据，并返回删除数量。"""
    with _connect() as connection:
        row = connection.execute(text("SELECT COUNT(*) AS count FROM documents")).mappings().first()
        removed_count = int(row["count"])
        connection.execute(text("DELETE FROM documents"))
    return removed_count


