def reserve_document_fingerprint(
    file_hash: str,
    document_id: str,
    filename: str,
    file_path: Path,
) -> dict[str, Any]:
    """原子地登记文件指纹，保证同一内容不会被并发重复处理。"""
    now = utc_now()
    with _connect() as connection:
        inserted = connection.execute(
            text(
                """
                INSERT INTO document_fingerprints
                (file_hash, document_id, status, filename, file_path, created_at, updated_at)
                VALUES (:file_hash, :document_id, 'processing', :filename, :file_path, :created_at, :updated_at)
                ON CONFLICT (file_hash) DO NOTHING
                RETURNING file_hash, document_id, status, filename, file_path
                """
            ),
            {
                "file_hash": file_hash,
                "document_id": document_id,
                "filename": filename,
                "file_path": str(file_path),
                "created_at": now,
                "updated_at": now,
            },
        ).mappings().first()
        if inserted:
            return {
                "reserved": True,
                "document_id": inserted["document_id"],
                "status": "processing",
            }

        reclaimed = connection.execute(
            text(
                """
                UPDATE document_fingerprints
                SET document_id = :document_id, status = 'processing',
                    filename = :filename, file_path = :file_path, updated_at = :updated_at
                WHERE file_hash = :file_hash AND status = 'failed'
                RETURNING document_id
                """
            ),
            {
                "file_hash": file_hash,
                "document_id": document_id,
                "filename": filename,
                "file_path": str(file_path),
                "updated_at": now,
            },
        ).mappings().first()
        if reclaimed:
            return {
                "reserved": True,
                "document_id": reclaimed["document_id"],
                "status": "processing",
                "reclaimed": True,
            }

        row = connection.execute(
            text("SELECT * FROM document_fingerprints WHERE file_hash = :file_hash"),
            {"file_hash": file_hash},
        ).mappings().first()
        if not row:
            raise RuntimeError("Fingerprint reservation disappeared before it could be read.")
        return {
            "reserved": False,
            "document_id": row["document_id"],
            "status": row["status"],
            "filename": row["filename"],
            "file_path": row["file_path"],
        }


