def clear_upload_tracking() -> None:
    with _connect() as connection:
        connection.execute(text("DELETE FROM document_fingerprints"))
        connection.execute(text("DELETE FROM upload_batch_items"))
        connection.execute(text("DELETE FROM upload_batches"))


def mark_interrupted_uploads() -> None:
    """应用重启后，把未完成的本地任务标记为可重试的失败状态。"""
    status_params = {f"status_{index}": status for index, status in enumerate(PROCESSING_UPLOAD_ITEM_STATUSES)}
    status_placeholders = ", ".join(f":{key}" for key in status_params)
    batch_ids: list[str] = []
    with _connect() as connection:
        rows = connection.execute(
            text(
                "SELECT DISTINCT batch_id FROM upload_batch_items "
                f"WHERE status IN ({status_placeholders})"
            ),
            status_params,
        ).mappings().all()
        batch_ids = [row["batch_id"] for row in rows]
        connection.execute(
            text(
                "UPDATE upload_batch_items "
                "SET status = 'failed', error_stage = 'interrupted', "
                "error_message = :error_message, updated_at = :updated_at "
                f"WHERE status IN ({status_placeholders})"
            ),
            {
                **status_params,
                "error_message": "Application restarted before this file finished.",
                "updated_at": utc_now(),
            },
        )
        connection.execute(
            text(
                "UPDATE document_fingerprints SET status = 'failed', updated_at = :updated_at "
                "WHERE status = 'processing'"
            ),
            {"updated_at": utc_now()},
        )

    for batch_id in batch_ids:
        refresh_upload_batch(batch_id)
